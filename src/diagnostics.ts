import * as vscode from 'vscode';
import { checkWeakName } from './rules/badNames';
import { scanSource } from './scanner';
import { getConfig } from './config';
import { WeakNameViolation, NamingHelperConfig } from './types';

/** Diagnostic collection identifier */
export const DIAGNOSTIC_SOURCE = 'Naming Helper';

/**
 * Maps a configuration severity string to a VS Code DiagnosticSeverity.
 */
export function mapSeverity(severity: NamingHelperConfig['severity']): vscode.DiagnosticSeverity {
  switch (severity) {
    case 'Warning':
      return vscode.DiagnosticSeverity.Warning;
    case 'Information':
      return vscode.DiagnosticSeverity.Information;
    case 'Hint':
    default:
      return vscode.DiagnosticSeverity.Hint;
  }
}

/**
 * Checks whether a document should be excluded from scanning based on path or size.
 */
export function shouldExcludeDocument(
  document: vscode.TextDocument,
  config: NamingHelperConfig
): boolean {
  const uriPath = document.uri.fsPath.replace(/\\/g, '/');

  // Skip files over 5,000 lines
  if (document.lineCount > 5000) {
    return true;
  }

  // Check generated code comment at file start
  const firstLines = document.getText(
    new vscode.Range(0, 0, Math.min(5, document.lineCount - 1), 100)
  );
  if (
    /@generated|generated by|auto-generated|code generated by/i.test(firstLines)
  ) {
    return true;
  }

  // Check exclusion globs (node_modules, dist, .min.js, .d.ts)
  for (const glob of config.excludeGlobs) {
    const cleanPattern = glob
      .replace(/^\*\*\//, '')
      .replace(/\/\*\*$/, '')
      .replace(/\*\*/g, '.*')
      .replace(/\*/g, '[^/]*');
    try {
      const regex = new RegExp(cleanPattern, 'i');
      if (regex.test(uriPath)) {
        return true;
      }
    } catch {
      // Fallback simple substring check
      const sub = glob.replace(/\*/g, '');
      if (sub && uriPath.includes(sub)) {
        return true;
      }
    }
  }

  return false;
}

/**
 * Analyzes a text document and returns weak name violations.
 */
export function analyzeDocument(
  document: vscode.TextDocument,
  config: NamingHelperConfig
): WeakNameViolation[] {
  if (!config.enable || shouldExcludeDocument(document, config)) {
    return [];
  }

  const text = document.getText();
  const scanResult = scanSource(text, document.fileName);
  const violations: WeakNameViolation[] = [];

  for (const decl of scanResult.declarations) {
    const violation = checkWeakName(decl, config, scanResult.scopes);
    if (violation) {
      violations.push(violation);
    }
  }

  return violations;
}

/**
 * Diagnostics manager responsible for updating the VS Code diagnostic collection.
 */
export class DiagnosticsManager {
  private diagnosticCollection: vscode.DiagnosticCollection;
  private pendingDebounceTimers = new Map<string, NodeJS.Timeout>();
  private activeViolations = new Map<string, WeakNameViolation[]>();

  constructor() {
    this.diagnosticCollection =
      vscode.languages.createDiagnosticCollection('naming-helper');
  }

  /**
   * Get currently active violations for a given URI string.
   */
  public getViolationsForUri(uriString: string): WeakNameViolation[] {
    return this.activeViolations.get(uriString) ?? [];
  }

  /**
   * Clears diagnostics and violations for a closed document.
   */
  public handleDocumentClosed(document: vscode.TextDocument): void {
    const key = document.uri.toString();
    const timer = this.pendingDebounceTimers.get(key);
    if (timer) {
      clearTimeout(timer);
      this.pendingDebounceTimers.delete(key);
    }
    this.diagnosticCollection.delete(document.uri);
    this.activeViolations.delete(key);
  }

  /**
   * Triggers an immediate or debounced scan of the given document.
   */
  public scheduleScan(document: vscode.TextDocument, immediate: boolean = false): void {
    const supportedLanguages = [
      'javascript',
      'typescript',
      'javascriptreact',
      'typescriptreact',
    ];
    if (!supportedLanguages.includes(document.languageId)) {
      return;
    }

    const config = getConfig();
    const key = document.uri.toString();

    const existingTimer = this.pendingDebounceTimers.get(key);
    if (existingTimer) {
      clearTimeout(existingTimer);
      this.pendingDebounceTimers.delete(key);
    }

    const runScan = () => {
      this.pendingDebounceTimers.delete(key);
      const violations = analyzeDocument(document, config);
      this.activeViolations.set(key, violations);

      const diagnostics: vscode.Diagnostic[] = violations.map((v) => {
        const range = new vscode.Range(
          v.range.start.line,
          v.range.start.character,
          v.range.end.line,
          v.range.end.character
        );
        const diagnostic = new vscode.Diagnostic(
          range,
          `${v.message} ${v.namingTip}`,
          mapSeverity(config.severity)
        );
        diagnostic.source = DIAGNOSTIC_SOURCE;
        diagnostic.code = v.ruleId;
        return diagnostic;
      });

      this.diagnosticCollection.set(document.uri, diagnostics);
    };

    if (immediate || config.debounceMs <= 0) {
      runScan();
    } else {
      const timer = setTimeout(runScan, config.debounceMs);
      this.pendingDebounceTimers.set(key, timer);
    }
  }

  /**
   * Disposes the diagnostic collection and cancels all active timers.
   */
  public dispose(): void {
    for (const timer of this.pendingDebounceTimers.values()) {
      clearTimeout(timer);
    }
    this.pendingDebounceTimers.clear();
    this.diagnosticCollection.dispose();
    this.activeViolations.clear();
  }
}

